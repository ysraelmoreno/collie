#!/bin/zsh -f
# escapes.sh: escape routes under probe.sb (run inside via sbrun.sh <repo> zsh -f escapes.sh). OK = expected outcome.
H=$HOME; C=${COLLIE_DIR}; outside=$1
t() { local want=$1; shift; if eval "$@" >/dev/null 2>&1; then got=allowed; else got=denied; fi
      [[ $got == $want ]] && r=OK || r=FAIL; printf '%-4s %-8s %s\n' $r $got "$*"; }
t denied "cat $H/.ssh/id_ed25519"
t allowed "cat $H/.ssh/known_hosts"
t allowed "cat $H/.ssh/config"
t denied "cat $H/.aws/credentials"
t denied "cat $H/.config/gh/hosts.yml"
t denied "cat $H/.netrc"
t denied "cat $H/Documents/doc.txt"
t denied "ls $H"
t allowed "test -d $H/Documents"
t allowed "cat $H/.gitconfig"
t denied "echo x >> $H/.zshrc"
t denied "echo x >> $H/.gitconfig"
t allowed "echo x > ./scratch.txt"
t allowed "mkdir -p .claude && echo '{}' > .claude/settings.json"
t denied "echo x > .git/hooks/pre-commit"
t denied "echo x >> .git/config"
t denied "git config spike.x 1"
t denied "echo x > .git/config.tmp && mv .git/config.tmp .git/config"
t denied "mkdir -p .git/info && echo x > .git/info/attributes"
t denied "rm -rf .git/hooks"
t denied "mv .git/hooks .git/hooks.old"
t denied "ln -s /tmp .git/hooks2 && mv .git/hooks2 .git/hooks"
t denied "mv .git .gitold"
t denied "cat $C/admin-token"
t denied "ls $C"
t allowed "python3 -c 'import socket,sys;s=socket.socket(socket.AF_UNIX);s.connect(sys.argv[1]);assert s.recv(3)' $C/daemon.sock"
t denied "python3 -c 'import socket,sys;s=socket.socket(socket.AF_UNIX);s.connect(sys.argv[1]);assert s.recv(3)' $C/other.sock"
t denied "/usr/bin/security list-keychains"
t denied "kill -CONT $outside"
t allowed "sleep 5 & kill \$!"
t allowed "ps -o pid= -p \$\$"
t denied "ln -s $H/.ssh/id_ed25519 ./lnk && cat ./lnk"
t denied "ln ./../home/.ssh/id_ed25519 ./hard 2>/dev/null || ln $H/.ssh/id_ed25519 ./hard; cat ./hard"
t allowed "echo x > /tmp/sbspike-w && rm /tmp/sbspike-w"
t allowed "osascript -e 'return 1'"
